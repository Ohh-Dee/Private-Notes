fn main() {
    let apples_num = 5;
    // to assign a var use let then the var name then = then the value
    let oranges = 14 + 6;
    let fruits = apples_num + oranges;
    /*
    You will want to use your variables first put in your string then input {} for dynamtic input
    then after the "" put a , and then put which variable you want to show up in order./
    */
    println!(
        "This year my garden has {} apples and {} oranges for a total of {} fruits",
        apples_num, oranges, fruits
    );
}
